);

CREATE TABLE public.categories (
    category_id integer GENERATED BY DEFAULT AS IDENTITY,
    organization_id integer NOT NULL
        REFERENCES public.organizations(organization_id),
    category_name varchar(100) NOT NULL,
    description text,
    PRIMARY KEY (category_id),
    CONSTRAINT uq_categories_org_id UNIQUE (organization_id, category_id),
    CONSTRAINT uq_categories_org_name UNIQUE (organization_id, category_name)
);

CREATE TABLE public.products (
    product_id integer GENERATED BY DEFAULT AS IDENTITY,
    organization_id integer NOT NULL
        REFERENCES public.organizations(organization_id),
    product_name varchar(150) NOT NULL,
    sku varchar(50) NOT NULL,
    category_id integer,
    description text,
    price numeric(12, 2) NOT NULL DEFAULT 0 CHECK (price >= 0),
    quantity integer NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    reorder_point integer NOT NULL DEFAULT 50 CHECK (reorder_point >= 0),
    upc varchar(12),
    variant varchar(200),
    is_deleted boolean NOT NULL DEFAULT false,
    deleted_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (product_id),
    CONSTRAINT uq_products_org_id UNIQUE (organization_id, product_id),
    CONSTRAINT uq_products_org_sku UNIQUE (organization_id, sku),
    CONSTRAINT fk_products_org_category
        FOREIGN KEY (organization_id, category_id)
        REFERENCES public.categories(organization_id, category_id)
        ON DELETE SET NULL (category_id)
);

