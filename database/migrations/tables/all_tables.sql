CREATE TABLE public.users (
    user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name varchar(160) NOT NULL,
    username varchar(50),
    email varchar(320) NOT NULL UNIQUE,
    password_hash text NOT NULL,
    role varchar(20) NOT NULL DEFAULT 'staff'
        CHECK (role IN ('owner', 'manager', 'staff')),
    is_active boolean NOT NULL DEFAULT true,
    is_deleted boolean NOT NULL DEFAULT false,
    deleted_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.organizations (
    organization_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_name varchar(160) NOT NULL,
    created_by_email varchar(320) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE public.organization_memberships (
    organization_id integer NOT NULL
        REFERENCES public.organizations(organization_id) ON DELETE CASCADE,
    email varchar(320) NOT NULL,
    role varchar(20) NOT NULL CHECK (role IN ('owner', 'manager', 'staff')),
    status varchar(20) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'account_deleted')),
    joined_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (organization_id, email)
);

CREATE TABLE public.organization_invitations (
