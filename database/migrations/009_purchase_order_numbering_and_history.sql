BEGIN;

ALTER TABLE public.purchase_orders
    ADD COLUMN order_number bigint,
    ADD COLUMN deleted_at timestamptz,
    ADD COLUMN deleted_by_email varchar(320);

WITH numbered AS (
    SELECT organization_id, order_id,
           row_number() OVER (
               PARTITION BY organization_id
               ORDER BY created_at, order_id
           ) AS order_number
    FROM public.purchase_orders
)
UPDATE public.purchase_orders AS purchase_order
SET order_number = numbered.order_number
FROM numbered
WHERE numbered.organization_id = purchase_order.organization_id
  AND numbered.order_id = purchase_order.order_id;

ALTER TABLE public.purchase_orders
    ALTER COLUMN order_number SET NOT NULL,
    ADD CONSTRAINT uq_purchase_orders_org_number
        UNIQUE (organization_id, order_number);

CREATE INDEX ix_purchase_orders_org_active_created
    ON public.purchase_orders (organization_id, created_at DESC, order_id DESC)
    WHERE deleted_at IS NULL;

CREATE TABLE public.purchase_order_history (
    event_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id integer NOT NULL,
    order_id bigint NOT NULL,
    event_type text NOT NULL CHECK (
        event_type IN ('created', 'updated', 'received', 'deleted')
    ),
    actor_email varchar(320) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    details jsonb NOT NULL DEFAULT '{}'::jsonb,
    CONSTRAINT fk_purchase_order_history_order
        FOREIGN KEY (organization_id, order_id)
        REFERENCES public.purchase_orders (organization_id, order_id)
        ON DELETE CASCADE
);

CREATE INDEX ix_purchase_order_history_org_event
    ON public.purchase_order_history (organization_id, event_id DESC);

INSERT INTO public.purchase_order_history (
    organization_id, order_id, event_type, actor_email, created_at, details
)
SELECT purchase_order.organization_id, purchase_order.order_id, 'created',
       purchase_order.created_by_email, purchase_order.created_at,
       jsonb_build_object(
           'notes', purchase_order.notes,
           'items', COALESCE((
               SELECT jsonb_agg(jsonb_build_object(
                   'product_id', item.product_id,
                   'product_name', product.product_name,
                   'sku', product.sku,
                   'quantity_ordered', item.quantity_ordered,
                   'quantity_received', item.quantity_received
               ) ORDER BY item.item_id)
               FROM public.purchase_order_items AS item
               JOIN public.products AS product
                 ON product.organization_id = item.organization_id
                AND product.product_id = item.product_id
               WHERE item.organization_id = purchase_order.organization_id
                 AND item.order_id = purchase_order.order_id
           ), '[]'::jsonb)
       )
FROM public.purchase_orders AS purchase_order
ORDER BY purchase_order.created_at, purchase_order.order_id;

CREATE OR REPLACE FUNCTION public.stockwise_assign_purchase_order_number()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
    PERFORM pg_advisory_xact_lock(92031, NEW.organization_id);
    SELECT COALESCE(MAX(order_number), 0) + 1
    INTO NEW.order_number
    FROM public.purchase_orders
    WHERE organization_id = NEW.organization_id;
    RETURN NEW;
END;
$function$;

CREATE TRIGGER trg_stockwise_assign_purchase_order_number
BEFORE INSERT ON public.purchase_orders
FOR EACH ROW EXECUTE FUNCTION public.stockwise_assign_purchase_order_number();

CREATE OR REPLACE FUNCTION public.stockwise_purchase_order_history_trigger()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
DECLARE
    v_event_type text;
    v_actor text;
    v_details jsonb;
BEGIN
    IF TG_OP = 'INSERT' THEN
        v_event_type := 'created';
        v_actor := NEW.created_by_email;
        v_details := jsonb_build_object(
            'notes', NEW.notes,
            'items', COALESCE((
                SELECT jsonb_agg(jsonb_build_object(
                    'product_id', item.product_id,
                    'product_name', product.product_name,
                    'sku', product.sku,
                    'quantity_ordered', item.quantity_ordered,
                    'quantity_received', item.quantity_received
                ) ORDER BY item.item_id)
                FROM public.purchase_order_items AS item
                JOIN public.products AS product
                  ON product.organization_id = item.organization_id
                 AND product.product_id = item.product_id
                WHERE item.organization_id = NEW.organization_id
                  AND item.order_id = NEW.order_id
            ), '[]'::jsonb)
        );
    ELSIF OLD.deleted_at IS NULL AND NEW.deleted_at IS NOT NULL THEN
        v_event_type := 'deleted';
        v_actor := COALESCE(NEW.deleted_by_email, NEW.created_by_email);
        v_details := jsonb_build_object(
            'notes', NEW.notes,
            'items', COALESCE((
                SELECT jsonb_agg(jsonb_build_object(
                    'product_id', item.product_id,
                    'product_name', product.product_name,
                    'sku', product.sku,
                    'quantity_ordered', item.quantity_ordered,
                    'quantity_received', item.quantity_received
                ) ORDER BY item.item_id)
                FROM public.purchase_order_items AS item
                JOIN public.products AS product
                  ON product.organization_id = item.organization_id
                 AND product.product_id = item.product_id
                WHERE item.organization_id = NEW.organization_id
                  AND item.order_id = NEW.order_id
            ), '[]'::jsonb),
            'received_item_count', (
                SELECT count(*) FROM public.purchase_order_items AS item
                WHERE item.organization_id = NEW.organization_id
                  AND item.order_id = NEW.order_id
                  AND item.quantity_received > 0
            )
        );
    ELSE
        v_event_type := 'updated';
        v_actor := COALESCE(
            NULLIF(current_setting('app.actor_email', true), ''),
            NEW.created_by_email
        );
        v_details := jsonb_build_object(
            'notes', NEW.notes,
            'items', COALESCE((
                SELECT jsonb_agg(jsonb_build_object(
                    'product_id', item.product_id,
                    'product_name', product.product_name,
                    'sku', product.sku,
                    'quantity_ordered', item.quantity_ordered,
                    'quantity_received', item.quantity_received
                ) ORDER BY item.item_id)
                FROM public.purchase_order_items AS item
                JOIN public.products AS product
                  ON product.organization_id = item.organization_id
                 AND product.product_id = item.product_id
                WHERE item.organization_id = NEW.organization_id
                  AND item.order_id = NEW.order_id
            ), '[]'::jsonb)
        );
    END IF;

    INSERT INTO public.purchase_order_history (
        organization_id, order_id, event_type, actor_email, details
    ) VALUES (
        NEW.organization_id, NEW.order_id, v_event_type, v_actor, v_details
    );
    RETURN NEW;
END;
$function$;

CREATE CONSTRAINT TRIGGER trg_stockwise_purchase_order_created
AFTER INSERT ON public.purchase_orders
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION public.stockwise_purchase_order_history_trigger();

CREATE CONSTRAINT TRIGGER trg_stockwise_purchase_order_updated
AFTER UPDATE OF notes, deleted_at ON public.purchase_orders
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION public.stockwise_purchase_order_history_trigger();

CREATE OR REPLACE FUNCTION public.stockwise_purchase_order_item_history_trigger()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
DECLARE
    v_actor text;
BEGIN
    v_actor := COALESCE(
        NULLIF(current_setting('app.actor_email', true), ''),
        (SELECT purchase_order.created_by_email
         FROM public.purchase_orders AS purchase_order
         WHERE purchase_order.organization_id = NEW.organization_id
           AND purchase_order.order_id = NEW.order_id)
    );
    INSERT INTO public.purchase_order_history (
        organization_id, order_id, event_type, actor_email, details
    ) VALUES (
        NEW.organization_id,
        NEW.order_id,
        'received',
        v_actor,
        jsonb_build_object(
            'product_id', NEW.product_id,
            'product_name', (
                SELECT product.product_name
                FROM public.products AS product
                WHERE product.organization_id = NEW.organization_id
                  AND product.product_id = NEW.product_id
            ),
            'quantity_received', NEW.quantity_received - OLD.quantity_received,
            'total_received', NEW.quantity_received,
            'quantity_ordered', NEW.quantity_ordered
        )
    );
    RETURN NEW;
END;
$function$;

CREATE TRIGGER trg_stockwise_purchase_order_item_received
AFTER UPDATE OF quantity_received ON public.purchase_order_items
FOR EACH ROW
WHEN (OLD.quantity_received IS DISTINCT FROM NEW.quantity_received)
EXECUTE FUNCTION public.stockwise_purchase_order_item_history_trigger();

CREATE OR REPLACE FUNCTION public.stockwise_guard_deleted_purchase_order_item()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
    IF EXISTS (
        SELECT 1 FROM public.purchase_orders AS purchase_order
        WHERE purchase_order.organization_id = NEW.organization_id
          AND purchase_order.order_id = NEW.order_id
          AND purchase_order.deleted_at IS NOT NULL
    ) THEN
        RAISE EXCEPTION 'A deleted purchase order cannot be changed'
            USING ERRCODE = '22023';
    END IF;
    RETURN NEW;
END;
$function$;

CREATE TRIGGER trg_stockwise_guard_deleted_purchase_order_item
BEFORE INSERT OR UPDATE ON public.purchase_order_items
FOR EACH ROW EXECUTE FUNCTION public.stockwise_guard_deleted_purchase_order_item();

DROP FUNCTION public.stockwise_get_purchase_orders(integer, bigint, integer);

CREATE FUNCTION public.stockwise_get_purchase_orders(
    p_organization_id integer,
    p_order_id bigint DEFAULT NULL,
    p_limit integer DEFAULT 100
)
RETURNS TABLE(
    order_id bigint,
    order_number bigint,
    notes text,
    created_by_email text,
    created_at timestamptz,
    status text,
    item_id bigint,
    product_id integer,
    product_name text,
    sku text,
    quantity_ordered integer,
    quantity_received integer
)
LANGUAGE sql
STABLE
AS $function$
    WITH selected_orders AS (
        SELECT purchase_order.order_id, purchase_order.order_number
        FROM public.purchase_orders AS purchase_order
        WHERE purchase_order.organization_id = p_organization_id
          AND purchase_order.deleted_at IS NULL
          AND (p_order_id IS NULL OR purchase_order.order_id = p_order_id)
        ORDER BY purchase_order.created_at DESC, purchase_order.order_id DESC
        LIMIT LEAST(GREATEST(COALESCE(p_limit, 100), 1), 200)
    ),
    order_status AS (
        SELECT item.organization_id, item.order_id,
               CASE
                   WHEN bool_and(item.quantity_received = item.quantity_ordered)
                       THEN 'Received'
                   WHEN bool_or(item.quantity_received > 0)
                       THEN 'Partially received'
                   ELSE 'Open'
               END AS status
        FROM public.purchase_order_items AS item
        JOIN selected_orders AS selected ON selected.order_id = item.order_id
        GROUP BY item.organization_id, item.order_id
    )
    SELECT purchase_order.order_id, purchase_order.order_number,
           purchase_order.notes, purchase_order.created_by_email,
           purchase_order.created_at, order_status.status, item.item_id,
           product.product_id, product.product_name::text, product.sku::text,
           item.quantity_ordered, item.quantity_received
    FROM selected_orders AS selected
    JOIN public.purchase_orders AS purchase_order
      ON purchase_order.organization_id = p_organization_id
     AND purchase_order.order_id = selected.order_id
    JOIN order_status
      ON order_status.organization_id = purchase_order.organization_id
     AND order_status.order_id = purchase_order.order_id
    JOIN public.purchase_order_items AS item
      ON item.organization_id = purchase_order.organization_id
     AND item.order_id = purchase_order.order_id
    JOIN public.products AS product
      ON product.organization_id = item.organization_id
     AND product.product_id = item.product_id
    ORDER BY purchase_order.created_at DESC, purchase_order.order_id DESC,
             item.item_id;
$function$;

CREATE OR REPLACE FUNCTION public.stockwise_get_purchase_order_history(
    p_organization_id integer,
    p_limit integer DEFAULT 200
)
RETURNS TABLE(
    event_id bigint,
    order_id bigint,
    order_number bigint,
    event_type text,
    actor_email text,
    created_at timestamptz,
    details jsonb
)
LANGUAGE sql
STABLE
AS $function$
    SELECT history.event_id, history.order_id, purchase_order.order_number,
           history.event_type, history.actor_email, history.created_at,
           history.details
    FROM public.purchase_order_history AS history
    JOIN public.purchase_orders AS purchase_order
      ON purchase_order.organization_id = history.organization_id
     AND purchase_order.order_id = history.order_id
    WHERE history.organization_id = p_organization_id
    ORDER BY history.event_id DESC
    LIMIT LEAST(GREATEST(COALESCE(p_limit, 200), 1), 500);
$function$;

CREATE OR REPLACE FUNCTION public.stockwise_delete_purchase_order(
    p_organization_id integer,
    p_email text,
    p_order_id bigint
)
RETURNS boolean
LANGUAGE plpgsql
AS $function$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM public.organization_memberships AS membership
        WHERE membership.organization_id = p_organization_id
          AND lower(membership.email) = lower(btrim(p_email))
          AND membership.status = 'active'
    ) THEN
        RAISE EXCEPTION 'User is not an active member of this organization'
            USING ERRCODE = '42501';
    END IF;

    UPDATE public.purchase_orders
    SET deleted_at = CURRENT_TIMESTAMP,
        deleted_by_email = lower(btrim(p_email))
    WHERE organization_id = p_organization_id
      AND order_id = p_order_id
      AND deleted_at IS NULL;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'Purchase order was not found'
            USING ERRCODE = 'P0002';
    END IF;
    RETURN TRUE;
END;
$function$;

CREATE OR REPLACE FUNCTION public.stockwise_prevent_delete_open_order_product()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
    IF OLD.is_deleted = false
       AND NEW.is_deleted = true
       AND EXISTS (
           SELECT 1
           FROM public.purchase_order_items AS item
           JOIN public.purchase_orders AS purchase_order
             ON purchase_order.organization_id = item.organization_id
            AND purchase_order.order_id = item.order_id
           WHERE item.organization_id = OLD.organization_id
             AND item.product_id = OLD.product_id
             AND item.quantity_received < item.quantity_ordered
             AND purchase_order.deleted_at IS NULL
       ) THEN
        RAISE EXCEPTION
            'This product cannot be deleted while a purchase order has quantity remaining'
            USING ERRCODE = '22023';
    END IF;
    RETURN NEW;
END;
$function$;

