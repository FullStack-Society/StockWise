CREATE OR REPLACE FUNCTION public.organization_update_inventory(
    p_organization_id integer,
    p_product_id integer,
    p_product_name text,
    p_sku text,
    p_category_id integer,
    p_description text,
    p_price numeric,
    p_quantity integer,
    p_location_id integer,
    p_reorder_point integer
)
RETURNS TABLE(
    product_id integer, product_name text, sku text, category_id integer,
    description text, price numeric, quantity integer, reorder_point integer,
    location_id integer, location_name text, created_at timestamptz,
    updated_at timestamptz, category_name text, status text
)
LANGUAGE plpgsql
AS $function$
BEGIN
    IF NULLIF(btrim(p_product_name), '') IS NULL
       OR NULLIF(btrim(p_sku), '') IS NULL THEN
        RAISE EXCEPTION 'Product name and SKU are required'
            USING ERRCODE = '22023';
    END IF;
    IF p_price IS NULL OR p_quantity IS NULL OR p_reorder_point IS NULL
       OR p_price < 0 OR p_quantity < 0 OR p_reorder_point < 0 THEN
        RAISE EXCEPTION
            'Price, quantity, and reorder point must be non-negative'
            USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (
        SELECT 1
        FROM public.inventory_location_stock AS stock
        JOIN public.inventory_locations AS location
          ON location.organization_id = stock.organization_id
         AND location.location_id = stock.location_id
        WHERE stock.organization_id = p_organization_id
          AND stock.product_id = p_product_id
          AND stock.location_id = p_location_id
          AND location.is_active = true
    ) THEN
        RAISE EXCEPTION 'Product or inventory location was not found'
            USING ERRCODE = 'P0002';
    END IF;

    UPDATE public.products AS product
    SET product_name = btrim(p_product_name),
        sku = btrim(p_sku),
        category_id = p_category_id,
        description = p_description,
        price = p_price,
        updated_at = CURRENT_TIMESTAMP
    WHERE product.organization_id = p_organization_id
      AND product.product_id = p_product_id
      AND product.is_deleted = false;
    IF NOT FOUND THEN
        RETURN;
    END IF;

    UPDATE public.inventory_location_stock AS stock
    SET reorder_point = p_reorder_point,
        updated_at = CURRENT_TIMESTAMP
    WHERE stock.organization_id = p_organization_id
      AND stock.product_id = p_product_id
      AND stock.location_id = p_location_id;

    RETURN QUERY
    SELECT *
    FROM public.organization_get_inventory_by_id(
        p_organization_id, p_product_id, p_location_id
    );
END;
$function$;

