CREATE OR REPLACE FUNCTION public.stockwise_create_inventory_location(
    p_organization_id integer,
    p_location_name text
)
RETURNS TABLE(location_id integer, location_name text, created_at timestamptz)
LANGUAGE plpgsql
AS $function$
DECLARE
    v_location_id integer;
BEGIN
    IF NULLIF(btrim(p_location_name), '') IS NULL
       OR length(btrim(p_location_name)) > 120 THEN
        RAISE EXCEPTION 'Location name must be between 1 and 120 characters'
            USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.organizations AS o
        WHERE o.organization_id = p_organization_id
    ) THEN
        RAISE EXCEPTION 'Organization was not found' USING ERRCODE = 'P0002';
    END IF;

    INSERT INTO public.inventory_locations (organization_id, location_name)
    VALUES (p_organization_id, btrim(p_location_name))
    RETURNING inventory_locations.location_id INTO v_location_id;

    INSERT INTO public.inventory_location_stock (
        organization_id, location_id, product_id, quantity
    )
    SELECT p_organization_id, v_location_id, p.product_id, 0
    FROM public.products AS p
    WHERE p.organization_id = p_organization_id
      AND p.is_deleted = false;

    RETURN QUERY
    SELECT l.location_id, l.location_name::text, l.created_at
    FROM public.inventory_locations AS l
    WHERE l.location_id = v_location_id;
END;
$function$;

CREATE OR REPLACE FUNCTION public.organization_create_inventory(
    p_organization_id integer,
    p_product_name text,
    p_sku text,
    p_category_id integer,
    p_description text,
    p_price numeric,
    p_quantity integer,
    p_location_id integer,
    p_reorder_point integer,
    p_actor_email text
)
RETURNS TABLE(
    product_id integer, product_name text, sku text, category_id integer,
    description text, price numeric, quantity integer, reorder_point integer,
    location_id integer, location_name text, created_at timestamptz,
    updated_at timestamptz, category_name text, status text
)
LANGUAGE plpgsql
AS $function$
DECLARE
    v_product_id integer;
BEGIN
    IF NULLIF(btrim(p_product_name), '') IS NULL
       OR NULLIF(btrim(p_sku), '') IS NULL THEN
        RAISE EXCEPTION 'Product name and SKU are required'
            USING ERRCODE = '22023';
    END IF;
    IF p_price IS NULL OR p_quantity IS NULL OR p_reorder_point IS NULL
       OR p_price < 0 OR p_quantity < 0 OR p_reorder_point < 0 THEN
        RAISE EXCEPTION
            'Price, quantity, and reorder point must be non-negative'
            USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.inventory_locations AS l
        WHERE l.organization_id = p_organization_id
          AND l.location_id = p_location_id AND l.is_active = true
    ) THEN
        RAISE EXCEPTION 'Inventory location was not found'
            USING ERRCODE = 'P0002';
    END IF;

    INSERT INTO public.products (
        organization_id, product_name, sku, category_id, description,
        price, quantity
    ) VALUES (
        p_organization_id, btrim(p_product_name), btrim(p_sku), p_category_id,
        p_description, p_price, p_quantity
    ) RETURNING products.product_id INTO v_product_id;

    INSERT INTO public.inventory_location_stock (
        organization_id, location_id, product_id, quantity, reorder_point
    )
    SELECT p_organization_id, l.location_id, v_product_id,
           CASE WHEN l.location_id = p_location_id THEN p_quantity ELSE 0 END,
           CASE WHEN l.location_id = p_location_id THEN p_reorder_point ELSE 50 END
    FROM public.inventory_locations AS l
    WHERE l.organization_id = p_organization_id AND l.is_active = true;

    IF p_quantity > 0 THEN
        INSERT INTO public.inventory_transactions (
            organization_id, location_id, product_id, user_id, actor_email,
            transaction_type, quantity, remarks
        ) VALUES (
            p_organization_id, p_location_id, v_product_id,
            (
                SELECT u.user_id FROM public.users AS u
                WHERE lower(u.email) = lower(btrim(p_actor_email))
                ORDER BY u.user_id LIMIT 1
            ),
            lower(btrim(p_actor_email)), 'IN', p_quantity, 'Opening stock'
        );
    END IF;

    RETURN QUERY SELECT * FROM public.organization_get_inventory_by_id(
        p_organization_id, v_product_id, p_location_id
    );
END;
$function$;

CREATE OR REPLACE FUNCTION public.organization_update_inventory(
    p_organization_id integer,
    p_product_id integer,
    p_product_name text,
    p_sku text,
    p_category_id integer,
    p_description text,
    p_price numeric,
    p_quantity integer,
    p_location_id integer,
    p_reorder_point integer
)
RETURNS TABLE(
    product_id integer, product_name text, sku text, category_id integer,
    description text, price numeric, quantity integer, reorder_point integer,
    location_id integer, location_name text, created_at timestamptz,
    updated_at timestamptz, category_name text, status text
)
LANGUAGE plpgsql
AS $function$
BEGIN
    IF NULLIF(btrim(p_product_name), '') IS NULL
       OR NULLIF(btrim(p_sku), '') IS NULL THEN
        RAISE EXCEPTION 'Product name and SKU are required'
            USING ERRCODE = '22023';
    END IF;
    IF p_price IS NULL OR p_quantity IS NULL OR p_reorder_point IS NULL
       OR p_price < 0 OR p_quantity < 0 OR p_reorder_point < 0 THEN
        RAISE EXCEPTION
            'Price, quantity, and reorder point must be non-negative'
            USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.inventory_location_stock AS s
        JOIN public.inventory_locations AS l
          ON l.organization_id = s.organization_id
         AND l.location_id = s.location_id
        WHERE s.organization_id = p_organization_id
          AND s.product_id = p_product_id
          AND s.location_id = p_location_id
          AND l.is_active = true
    ) THEN
        RAISE EXCEPTION 'Product or inventory location was not found'
            USING ERRCODE = 'P0002';
    END IF;

    UPDATE public.products AS p
    SET product_name = btrim(p_product_name), sku = btrim(p_sku),
        category_id = p_category_id, description = p_description,
        price = p_price, updated_at = CURRENT_TIMESTAMP
    WHERE p.organization_id = p_organization_id
      AND p.product_id = p_product_id
      AND p.is_deleted = false;
    IF NOT FOUND THEN RETURN; END IF;

    UPDATE public.inventory_location_stock
    SET reorder_point = p_reorder_point, updated_at = CURRENT_TIMESTAMP
    WHERE organization_id = p_organization_id
      AND product_id = p_product_id
      AND location_id = p_location_id;

    RETURN QUERY SELECT * FROM public.organization_get_inventory_by_id(
        p_organization_id, p_product_id, p_location_id
    );
END;
$function$;

CREATE OR REPLACE FUNCTION public.stockwise_adjust_location_stock(
    p_organization_id integer,
    p_email text,
    p_location_id integer,
    p_product_id integer,
    p_transaction_type text,
    p_quantity integer,
    p_remarks text
)
RETURNS integer
LANGUAGE plpgsql
AS $function$
DECLARE
    v_type text := upper(btrim(p_transaction_type));
    v_quantity integer;
BEGIN
    IF v_type NOT IN ('IN', 'OUT', 'ADJUST') THEN
        RAISE EXCEPTION 'Transaction type must be IN, OUT, or ADJUST'
            USING ERRCODE = '22023';
    END IF;
    IF p_quantity IS NULL
       OR (v_type = 'ADJUST' AND p_quantity = 0)
       OR (v_type <> 'ADJUST' AND p_quantity <= 0) THEN
        RAISE EXCEPTION 'Quantity must be non-zero, and movements must be positive'
            USING ERRCODE = '22023';
    END IF;
    IF NULLIF(btrim(p_remarks), '') IS NULL
       OR length(btrim(p_remarks)) > 500 THEN
        RAISE EXCEPTION 'A reason of up to 500 characters is required'
            USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.organization_memberships AS m
        WHERE m.organization_id = p_organization_id
          AND lower(m.email) = lower(btrim(p_email))
          AND m.status = 'active'
    ) THEN
        RAISE EXCEPTION 'User is not an active member of this organization'
            USING ERRCODE = '42501';
    END IF;

    SELECT s.quantity INTO v_quantity
    FROM public.inventory_location_stock AS s
    JOIN public.inventory_locations AS l
      ON l.organization_id = s.organization_id
     AND l.location_id = s.location_id
    JOIN public.products AS p
      ON p.organization_id = s.organization_id
     AND p.product_id = s.product_id
    WHERE s.organization_id = p_organization_id
      AND s.location_id = p_location_id
      AND s.product_id = p_product_id
      AND l.is_active = true
      AND p.is_deleted = false
    FOR UPDATE OF s;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Product or inventory location was not found'
            USING ERRCODE = 'P0002';
    END IF;
    IF (v_type = 'OUT' OR (v_type = 'ADJUST' AND p_quantity < 0))
       AND v_quantity < abs(p_quantity) THEN
        RAISE EXCEPTION 'Insufficient stock at this location'
            USING ERRCODE = '22023';
    END IF;
    IF (v_type = 'IN' OR (v_type = 'ADJUST' AND p_quantity > 0))
       AND v_quantity > 2147483647 - p_quantity THEN
        RAISE EXCEPTION 'Location quantity would exceed the supported limit'
            USING ERRCODE = '22023';
    END IF;

    UPDATE public.inventory_location_stock AS s
    SET quantity = CASE
            WHEN v_type = 'IN' THEN s.quantity + p_quantity
            WHEN v_type = 'OUT' THEN s.quantity - p_quantity
            ELSE s.quantity + p_quantity
        END,
        updated_at = CURRENT_TIMESTAMP
    WHERE s.organization_id = p_organization_id
      AND s.location_id = p_location_id
      AND s.product_id = p_product_id
    RETURNING s.quantity INTO v_quantity;

    UPDATE public.products AS p
    SET quantity = (
            SELECT COALESCE(SUM(s.quantity), 0)::integer
            FROM public.inventory_location_stock AS s
            WHERE s.organization_id = p_organization_id
              AND s.product_id = p_product_id
        ),
        updated_at = CURRENT_TIMESTAMP
    WHERE p.organization_id = p_organization_id
      AND p.product_id = p_product_id;

    INSERT INTO public.inventory_transactions (
        organization_id, location_id, product_id, user_id, actor_email,
        transaction_type, quantity, remarks
    ) VALUES (
        p_organization_id, p_location_id, p_product_id,
        (
            SELECT u.user_id FROM public.users AS u
            WHERE lower(u.email) = lower(btrim(p_email))
            ORDER BY u.user_id LIMIT 1
        ),
        lower(btrim(p_email)),
        CASE WHEN v_type = 'ADJUST'
             THEN CASE WHEN p_quantity > 0 THEN 'IN' ELSE 'OUT' END
             ELSE v_type END,
        abs(p_quantity),
        CASE WHEN v_type = 'ADJUST'
             THEN 'Adjustment: ' || btrim(p_remarks)
             ELSE btrim(p_remarks) END
    );
    RETURN v_quantity;
END;
$function$;

CREATE OR REPLACE PROCEDURE public.adjust_inventory_stock(
    IN p_product_id integer,
    IN p_user_id integer,
    IN p_transaction_type text,
    IN p_quantity integer,
    IN p_remarks text DEFAULT NULL
)
LANGUAGE plpgsql
AS $procedure$
DECLARE
    v_organization_id integer;
    v_email text;
    v_location_id integer;
BEGIN
    SELECT p.organization_id INTO v_organization_id
    FROM public.products AS p
    WHERE p.product_id = p_product_id AND p.is_deleted = false;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Product was not found' USING ERRCODE = 'P0002';
    END IF;

    SELECT lower(u.email) INTO v_email
    FROM public.users AS u
    WHERE u.user_id = p_user_id;
    IF v_email IS NULL THEN
        RAISE EXCEPTION 'User was not found' USING ERRCODE = '42501';
    END IF;

    SELECT l.location_id INTO v_location_id
    FROM public.inventory_locations AS l
    WHERE l.organization_id = v_organization_id
      AND l.location_name = 'Main Store'
      AND l.is_active = true;
    IF v_location_id IS NULL THEN
        RAISE EXCEPTION 'Default inventory location was not found'
            USING ERRCODE = 'P0002';
    END IF;

    PERFORM public.stockwise_adjust_location_stock(
        v_organization_id,
        v_email,
        v_location_id,
        p_product_id,
        p_transaction_type,
        p_quantity,
        COALESCE(NULLIF(btrim(p_remarks), ''), 'Legacy stock adjustment')
    );
END;
$procedure$;

CREATE OR REPLACE FUNCTION public.stockwise_record_stocktake(
    p_organization_id integer,
    p_email text,
    p_location_id integer,
    p_product_id integer,
    p_counted_quantity integer,
    p_remarks text
)
RETURNS integer
LANGUAGE plpgsql
AS $function$
DECLARE
    v_expected integer;
    v_delta integer;
    v_stocktake_id bigint;
BEGIN
    IF p_counted_quantity IS NULL OR p_counted_quantity < 0 THEN
        RAISE EXCEPTION 'Counted quantity must be zero or greater'
            USING ERRCODE = '22023';
    END IF;
    IF NULLIF(btrim(p_remarks), '') IS NULL
       OR length(btrim(p_remarks)) > 500 THEN
        RAISE EXCEPTION 'A stocktake note of up to 500 characters is required'
            USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.organization_memberships AS m
        WHERE m.organization_id = p_organization_id
          AND lower(m.email) = lower(btrim(p_email))
          AND m.status = 'active'
    ) THEN
        RAISE EXCEPTION 'User is not an active member of this organization'
            USING ERRCODE = '42501';
    END IF;

    SELECT s.quantity INTO v_expected
    FROM public.inventory_location_stock AS s
    JOIN public.inventory_locations AS l
      ON l.organization_id = s.organization_id
     AND l.location_id = s.location_id
    JOIN public.products AS p
      ON p.organization_id = s.organization_id
     AND p.product_id = s.product_id
    WHERE s.organization_id = p_organization_id
      AND s.location_id = p_location_id
      AND s.product_id = p_product_id
      AND l.is_active = true AND p.is_deleted = false
    FOR UPDATE OF s;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'Product or inventory location was not found'
            USING ERRCODE = 'P0002';
    END IF;

    v_delta := p_counted_quantity - v_expected;
    INSERT INTO public.inventory_stocktakes (
        organization_id, location_id, product_id, expected_quantity,
        counted_quantity, actor_email, remarks
    ) VALUES (
        p_organization_id, p_location_id, p_product_id, v_expected,
        p_counted_quantity, lower(btrim(p_email)), btrim(p_remarks)
    ) RETURNING stocktake_id INTO v_stocktake_id;

    IF v_delta <> 0 THEN
        UPDATE public.inventory_location_stock
        SET quantity = p_counted_quantity, updated_at = CURRENT_TIMESTAMP
        WHERE organization_id = p_organization_id
          AND location_id = p_location_id
          AND product_id = p_product_id;

        UPDATE public.products AS p
        SET quantity = (
                SELECT COALESCE(SUM(s.quantity), 0)::integer
                FROM public.inventory_location_stock AS s
                WHERE s.organization_id = p_organization_id
                  AND s.product_id = p_product_id
            ),
            updated_at = CURRENT_TIMESTAMP
        WHERE p.organization_id = p_organization_id
          AND p.product_id = p_product_id;

        INSERT INTO public.inventory_transactions (
            organization_id, location_id, product_id, user_id, actor_email,
            transaction_type, quantity, remarks
        ) VALUES (
            p_organization_id, p_location_id, p_product_id,
            (
                SELECT u.user_id FROM public.users AS u
                WHERE lower(u.email) = lower(btrim(p_email))
                ORDER BY u.user_id LIMIT 1
            ),
            lower(btrim(p_email)),
            CASE WHEN v_delta > 0 THEN 'IN' ELSE 'OUT' END,
            abs(v_delta),
            format('stocktake:%s %s', v_stocktake_id, btrim(p_remarks))
        );
    END IF;
    RETURN p_counted_quantity;
END;
$function$;

CREATE OR REPLACE FUNCTION public.stockwise_transfer_location_stock(
    p_organization_id integer,
    p_email text,
    p_source_location_id integer,
    p_destination_location_id integer,
    p_product_id integer,
    p_quantity integer,
    p_remarks text
)
RETURNS TABLE(source_quantity integer, destination_quantity integer)
LANGUAGE plpgsql
AS $function$
BEGIN
    IF p_source_location_id = p_destination_location_id THEN
        RAISE EXCEPTION 'Choose two different inventory locations'
            USING ERRCODE = '22023';
    END IF;
    IF p_quantity IS NULL OR p_quantity <= 0 THEN
        RAISE EXCEPTION 'Transfer quantity must be greater than zero'
            USING ERRCODE = '22023';
    END IF;
    IF NULLIF(btrim(p_remarks), '') IS NULL
       OR length(btrim(p_remarks)) > 500 THEN
        RAISE EXCEPTION 'A transfer reason of up to 500 characters is required'
            USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.organization_memberships AS m
        WHERE m.organization_id = p_organization_id
          AND lower(m.email) = lower(btrim(p_email))
          AND m.status = 'active'
    ) THEN
        RAISE EXCEPTION 'User is not an active member of this organization'
            USING ERRCODE = '42501';
    END IF;
    IF NOT EXISTS (
        SELECT 1
        FROM public.products AS p
        JOIN public.inventory_locations AS source
          ON source.organization_id = p.organization_id
         AND source.location_id = p_source_location_id
         AND source.is_active = true
        JOIN public.inventory_locations AS destination
          ON destination.organization_id = p.organization_id
         AND destination.location_id = p_destination_location_id
         AND destination.is_active = true
        WHERE p.organization_id = p_organization_id
          AND p.product_id = p_product_id
          AND p.is_deleted = false
    ) THEN
        RAISE EXCEPTION 'Product or inventory location was not found'
            USING ERRCODE = 'P0002';
    END IF;

    PERFORM s.location_id
    FROM public.inventory_location_stock AS s
    WHERE s.organization_id = p_organization_id
      AND s.product_id = p_product_id
      AND s.location_id IN (
          p_source_location_id, p_destination_location_id
      )
    ORDER BY s.location_id
    FOR UPDATE;

    SELECT s.quantity INTO source_quantity
    FROM public.inventory_location_stock AS s
    WHERE s.organization_id = p_organization_id
      AND s.location_id = p_source_location_id
      AND s.product_id = p_product_id;
    SELECT s.quantity INTO destination_quantity
    FROM public.inventory_location_stock AS s
    WHERE s.organization_id = p_organization_id
      AND s.location_id = p_destination_location_id
      AND s.product_id = p_product_id;
    IF source_quantity IS NULL OR destination_quantity IS NULL THEN
        RAISE EXCEPTION 'Product is not assigned to both locations'
            USING ERRCODE = 'P0002';
    END IF;
    IF source_quantity < p_quantity THEN
        RAISE EXCEPTION 'Insufficient stock at the source location'
            USING ERRCODE = '22023';
    END IF;
    IF destination_quantity > 2147483647 - p_quantity THEN
        RAISE EXCEPTION 'Destination quantity would exceed the supported limit'
            USING ERRCODE = '22023';
    END IF;

    UPDATE public.inventory_location_stock
    SET quantity = quantity - p_quantity, updated_at = CURRENT_TIMESTAMP
    WHERE organization_id = p_organization_id
      AND location_id = p_source_location_id
      AND product_id = p_product_id;
    UPDATE public.inventory_location_stock
    SET quantity = quantity + p_quantity, updated_at = CURRENT_TIMESTAMP
    WHERE organization_id = p_organization_id
      AND location_id = p_destination_location_id
      AND product_id = p_product_id;
    UPDATE public.products
    SET updated_at = CURRENT_TIMESTAMP
    WHERE organization_id = p_organization_id
      AND product_id = p_product_id;

    INSERT INTO public.inventory_location_transfers (
        organization_id, source_location_id, destination_location_id,
        product_id, quantity, actor_email, remarks
    ) VALUES (
        p_organization_id, p_source_location_id, p_destination_location_id,
        p_product_id, p_quantity, lower(btrim(p_email)), btrim(p_remarks)
    );
    source_quantity := source_quantity - p_quantity;
    destination_quantity := destination_quantity + p_quantity;
    RETURN NEXT;
END;
$function$;

CREATE OR REPLACE FUNCTION public.stockwise_get_inventory_history(
    p_organization_id integer,
    p_location_id integer,
    p_product_id integer DEFAULT NULL,
    p_limit integer DEFAULT 100
)
RETURNS TABLE(
    movement_id bigint,
    occurred_at timestamptz,
    transaction_type text,
    product_id integer,
    product_name text,
    sku text,
    quantity integer,
    expected_quantity integer,
    counted_quantity integer,
    actor_email text,
    remarks text
)
LANGUAGE sql
STABLE
AS $function$
    WITH events AS (
        SELECT public.stockwise_transaction_timestamp(t) AS occurred_at,
               CASE
                   WHEN upper(t.transaction_type) IN ('IN', 'STOCK_IN')
                       THEN 'IN'
                   WHEN upper(t.transaction_type) IN ('OUT', 'STOCK_OUT')
                       THEN 'OUT'
                   ELSE 'OTHER'
               END::text AS transaction_type,
               t.product_id, p.product_name::text, p.sku::text,
               t.quantity,
               NULL::integer AS expected_quantity,
               NULL::integer AS counted_quantity,
               COALESCE(t.actor_email, 'Unknown')::text AS actor_email,
               t.remarks::text
        FROM public.inventory_transactions AS t
        JOIN public.products AS p
          ON p.organization_id = t.organization_id
         AND p.product_id = t.product_id
        WHERE t.organization_id = p_organization_id
          AND t.location_id = p_location_id
          AND (p_product_id IS NULL OR t.product_id = p_product_id)
          AND COALESCE(t.remarks, '') NOT LIKE 'stocktake:%'
        UNION ALL
        SELECT st.created_at, 'STOCKTAKE'::text,
               st.product_id, p.product_name::text, p.sku::text,
               abs(st.counted_quantity - st.expected_quantity),
               st.expected_quantity, st.counted_quantity,
               st.actor_email::text, st.remarks::text
        FROM public.inventory_stocktakes AS st
        JOIN public.products AS p
          ON p.organization_id = st.organization_id
         AND p.product_id = st.product_id
        WHERE st.organization_id = p_organization_id
          AND st.location_id = p_location_id
          AND (p_product_id IS NULL OR st.product_id = p_product_id)
        UNION ALL
        SELECT transfer.created_at, 'TRANSFER_OUT'::text,
               transfer.product_id, p.product_name::text, p.sku::text,
               transfer.quantity, NULL::integer, NULL::integer,
               transfer.actor_email::text,
               ('Transfer to ' || destination.location_name || ': ' ||
                transfer.remarks)::text
        FROM public.inventory_location_transfers AS transfer
        JOIN public.products AS p
          ON p.organization_id = transfer.organization_id
         AND p.product_id = transfer.product_id
        JOIN public.inventory_locations AS destination
          ON destination.organization_id = transfer.organization_id
         AND destination.location_id = transfer.destination_location_id
        WHERE transfer.organization_id = p_organization_id
          AND transfer.source_location_id = p_location_id
          AND (p_product_id IS NULL OR transfer.product_id = p_product_id)
        UNION ALL
        SELECT transfer.created_at, 'TRANSFER_IN'::text,
               transfer.product_id, p.product_name::text, p.sku::text,
               transfer.quantity, NULL::integer, NULL::integer,
               transfer.actor_email::text,
               ('Transfer from ' || source.location_name || ': ' ||
                transfer.remarks)::text
        FROM public.inventory_location_transfers AS transfer
        JOIN public.products AS p
          ON p.organization_id = transfer.organization_id
         AND p.product_id = transfer.product_id
        JOIN public.inventory_locations AS source
          ON source.organization_id = transfer.organization_id
         AND source.location_id = transfer.source_location_id
        WHERE transfer.organization_id = p_organization_id
          AND transfer.destination_location_id = p_location_id
          AND (p_product_id IS NULL OR transfer.product_id = p_product_id)
    ),
    recent AS (
        SELECT * FROM events
        ORDER BY occurred_at DESC, product_id DESC
        LIMIT LEAST(GREATEST(p_limit, 1), 200)
    )
    SELECT row_number() OVER (ORDER BY recent.occurred_at DESC, recent.product_id DESC),
           recent.occurred_at, recent.transaction_type,
           recent.product_id, recent.product_name, recent.sku,
           recent.quantity, recent.expected_quantity, recent.counted_quantity,
           recent.actor_email, recent.remarks
    FROM recent
    ORDER BY recent.occurred_at DESC, recent.product_id DESC;
$function$;

CREATE OR REPLACE FUNCTION public.stockwise_get_reorder_summary(
    p_organization_id integer
)
RETURNS jsonb
LANGUAGE sql
STABLE
AS $function$
    WITH product_totals AS (
        SELECT s.product_id,
               SUM(s.quantity)::bigint AS quantity,
               SUM(s.reorder_point)::bigint AS reorder_point
        FROM public.inventory_location_stock AS s
        JOIN public.products AS p
          ON p.organization_id = s.organization_id
         AND p.product_id = s.product_id
        WHERE s.organization_id = p_organization_id
          AND p.is_deleted = false
        GROUP BY s.product_id
    )
    SELECT jsonb_build_object(
        'low_stock_count', COUNT(*) FILTER (
            WHERE quantity > 0 AND quantity <= reorder_point
        ),
        'critical_count', COUNT(*) FILTER (WHERE quantity <= 0)
    )
    FROM product_totals;
$function$;

COMMIT;

