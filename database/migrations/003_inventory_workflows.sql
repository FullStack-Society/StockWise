CREATE TABLE IF NOT EXISTS public.inventory_locations (
    location_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id integer NOT NULL
        REFERENCES public.organizations(organization_id) ON DELETE CASCADE,
    location_name varchar(120) NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_inventory_locations_org_id
        UNIQUE (organization_id, location_id),
    CONSTRAINT uq_inventory_locations_org_name
        UNIQUE (organization_id, location_name),
    CONSTRAINT ck_inventory_locations_name
        CHECK (length(btrim(location_name)) BETWEEN 1 AND 120)
);

CREATE TABLE IF NOT EXISTS public.inventory_location_stock (
    organization_id integer NOT NULL,
    location_id integer NOT NULL,
    product_id integer NOT NULL,
    quantity integer NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    reorder_point integer NOT NULL DEFAULT 50 CHECK (reorder_point >= 0),
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (organization_id, location_id, product_id),
    CONSTRAINT fk_location_stock_location
        FOREIGN KEY (organization_id, location_id)
        REFERENCES public.inventory_locations(organization_id, location_id)
        ON DELETE CASCADE,
    CONSTRAINT fk_location_stock_product
        FOREIGN KEY (organization_id, product_id)
        REFERENCES public.products(organization_id, product_id)
        ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS public.inventory_stocktakes (
    stocktake_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id integer NOT NULL,
    location_id integer NOT NULL,
    product_id integer NOT NULL,
    expected_quantity integer NOT NULL CHECK (expected_quantity >= 0),
    counted_quantity integer NOT NULL CHECK (counted_quantity >= 0),
    actor_email varchar(320) NOT NULL,
    remarks text,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_stocktakes_location
        FOREIGN KEY (organization_id, location_id)
        REFERENCES public.inventory_locations(organization_id, location_id),
    CONSTRAINT fk_stocktakes_product
        FOREIGN KEY (organization_id, product_id)
        REFERENCES public.products(organization_id, product_id)
);

CREATE TABLE IF NOT EXISTS public.inventory_location_transfers (
    transfer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    organization_id integer NOT NULL,
    source_location_id integer NOT NULL,
    destination_location_id integer NOT NULL,
    product_id integer NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    actor_email varchar(320) NOT NULL,
    remarks text NOT NULL,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_inventory_location_transfer_distinct_locations
        CHECK (source_location_id <> destination_location_id),
    CONSTRAINT fk_location_transfer_source
        FOREIGN KEY (organization_id, source_location_id)
        REFERENCES public.inventory_locations(organization_id, location_id),
    CONSTRAINT fk_location_transfer_destination
        FOREIGN KEY (organization_id, destination_location_id)
        REFERENCES public.inventory_locations(organization_id, location_id),
    CONSTRAINT fk_location_transfer_product
        FOREIGN KEY (organization_id, product_id)
        REFERENCES public.products(organization_id, product_id)
);

