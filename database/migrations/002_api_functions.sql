CREATE OR REPLACE FUNCTION public.stockwise_settings_get_password_account(
    p_email text
)
RETURNS TABLE(password_hash text, account_table text)
LANGUAGE sql
STABLE
AS $function$
    SELECT account.password_hash, account.account_table
    FROM (
        SELECT a.password_hash::text, 'auth_users'::text AS account_table, 1 AS priority
        FROM public.auth_users AS a
        WHERE lower(a.email) = lower(btrim(p_email))
          AND a.is_active = true AND a.is_deleted = false
        UNION ALL
        SELECT u.password_hash::text, 'users'::text AS account_table, 2 AS priority
        FROM public.users AS u
        WHERE lower(u.email) = lower(btrim(p_email))
          AND u.is_deleted = false
          AND NOT EXISTS (
              SELECT 1 FROM public.auth_users AS a
              WHERE lower(a.email) = lower(btrim(p_email))
                AND a.is_active = true AND a.is_deleted = false
          )
    ) AS account
    ORDER BY account.priority
    LIMIT 1;
$function$;

CREATE OR REPLACE FUNCTION public.stockwise_settings_update_password(
    p_email text, p_account_table text, p_password_hash text
)
RETURNS boolean
LANGUAGE plpgsql
AS $function$
BEGIN
    IF p_account_table = 'auth_users' THEN
        UPDATE public.auth_users
        SET password_hash = p_password_hash
        WHERE lower(email) = lower(btrim(p_email))
          AND is_active = true AND is_deleted = false;
        RETURN FOUND;
    ELSIF p_account_table = 'users' THEN
        UPDATE public.users
        SET password_hash = p_password_hash
        WHERE lower(email) = lower(btrim(p_email)) AND is_deleted = false;
        RETURN FOUND;
    END IF;
    RETURN false;
END;
$function$;

CREATE OR REPLACE FUNCTION public.stockwise_settings_delete_account(
    p_email text
)
RETURNS TABLE(owner_membership boolean, account_found boolean)
LANGUAGE plpgsql
AS $function$
DECLARE
    v_auth_count integer;
    v_user_count integer;
BEGIN
    owner_membership := EXISTS (
        SELECT 1
        FROM public.organization_memberships AS m
        WHERE lower(m.email) = lower(btrim(p_email))
          AND m.status = 'active'
          AND (
              m.role = 'owner'
              OR EXISTS (
                  SELECT 1 FROM public.auth_users AS a
                  WHERE lower(a.email) = lower(btrim(p_email))
                    AND lower(a.role) = 'owner'
              )
              OR EXISTS (
                  SELECT 1 FROM public.users AS u
                  WHERE lower(u.email) = lower(btrim(p_email))
                    AND lower(u.role) = 'owner'
              )
          )
    );
    IF owner_membership THEN
        account_found := true;
        RETURN NEXT;
        RETURN;
    END IF;

    UPDATE public.auth_users
    SET is_active = false, is_deleted = true,
        deleted_at = CURRENT_TIMESTAMP
    WHERE lower(email) = lower(btrim(p_email)) AND is_deleted = false;
    GET DIAGNOSTICS v_auth_count = ROW_COUNT;

    UPDATE public.users
    SET is_deleted = true, deleted_at = CURRENT_TIMESTAMP
    WHERE lower(email) = lower(btrim(p_email)) AND is_deleted = false;
    GET DIAGNOSTICS v_user_count = ROW_COUNT;

    account_found := v_auth_count > 0 OR v_user_count > 0;
    IF account_found THEN
        UPDATE public.organization_memberships
        SET status = 'account_deleted'
        WHERE lower(email) = lower(btrim(p_email)) AND status = 'active';
        UPDATE public.organization_invitations
        SET status = 'revoked', responded_at = CURRENT_TIMESTAMP
        WHERE lower(email) = lower(btrim(p_email)) AND status = 'pending';
    END IF;

    owner_membership := false;
    RETURN NEXT;
END;
$function$;

