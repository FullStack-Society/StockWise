CREATE OR REPLACE FUNCTION public.stockwise_inventory_status(
    p_quantity integer, p_reorder_point integer
)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $function$
    SELECT CASE
        WHEN p_quantity <= 0 THEN 'Critical'
