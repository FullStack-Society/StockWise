-- StockWise fresh Supabase install
-- Run only in a NEW Supabase project with no StockWise tables in public.
-- This combines the legacy base tables required by ordered migrations
-- with migrations 001 through 033. It is not an upgrade script.

BEGIN;

DO $fresh_install_guard$
DECLARE
    relation_name text;
    has_rows boolean;
BEGIN
    IF to_regclass('public.organizations') IS NOT NULL
       OR to_regclass('public.schema_migrations') IS NOT NULL THEN
        RAISE EXCEPTION
            'StockWise tables already exist. Do not run this fresh-install script on an existing database; apply only pending numbered migrations.';
    END IF;

    FOREACH relation_name IN ARRAY ARRAY[
        'categories', 'users', 'auth_users', 'products', 'inventory_transactions'
    ] LOOP
        IF to_regclass(format('public.%I', relation_name)) IS NOT NULL THEN
            EXECUTE format(
                'SELECT EXISTS (SELECT 1 FROM public.%I LIMIT 1)', relation_name
            ) INTO has_rows;
            IF has_rows THEN
                RAISE EXCEPTION
                    'Existing public.% table contains data; use numbered migrations instead.',
                    relation_name;
            END IF;
        END IF;
    END LOOP;
END;
$fresh_install_guard$;

-- Base tables expected by migration 001. Later migrations evolve these into
-- the current schema used by the backend.
CREATE TABLE IF NOT EXISTS public.categories (
    category_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name varchar(100) NOT NULL,
    description text,
    CONSTRAINT categories_category_name_key UNIQUE (category_name)
);

CREATE TABLE IF NOT EXISTS public.users (
    user_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name varchar(100) NOT NULL,
    username varchar(50) NOT NULL UNIQUE,
    email varchar(320) NOT NULL UNIQUE,
    password_hash text NOT NULL,
    role varchar(20) NOT NULL DEFAULT 'staff',
    position varchar(120) NOT NULL DEFAULT '',
    is_deleted boolean NOT NULL DEFAULT false,
    deleted_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT check_user_role CHECK (role IN ('admin', 'staff'))
);

CREATE TABLE IF NOT EXISTS public.auth_users (
    id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name varchar(160) NOT NULL,
    email varchar(320) NOT NULL UNIQUE,
    password_hash varchar(256) NOT NULL,
    role varchar(20) NOT NULL DEFAULT 'staff',
    is_active boolean NOT NULL DEFAULT true,
    is_deleted boolean NOT NULL DEFAULT false,
    deleted_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS public.products (
    product_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name varchar(150) NOT NULL,
    sku varchar(50) NOT NULL,
    category_id integer,
    description text,
    price numeric(12,2) NOT NULL DEFAULT 0 CHECK (price >= 0),
    quantity integer NOT NULL DEFAULT 0 CHECK (quantity >= 0),
    minimum_stock integer NOT NULL DEFAULT 5 CHECK (minimum_stock >= 0),
    is_deleted boolean NOT NULL DEFAULT false,
    deleted_at timestamptz,
    created_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT products_sku_key UNIQUE (sku),
    CONSTRAINT fk_product_category
        FOREIGN KEY (category_id) REFERENCES public.categories(category_id) ON DELETE SET NULL
);
CREATE INDEX IF NOT EXISTS idx_products_category ON public.products(category_id);

CREATE TABLE IF NOT EXISTS public.inventory_transactions (
    transaction_id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id integer NOT NULL,
    user_id integer NOT NULL,
    transaction_type varchar(20) NOT NULL,
    quantity integer NOT NULL CHECK (quantity > 0),
    remarks text,
    transaction_date timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_transaction_product
        FOREIGN KEY (product_id) REFERENCES public.products(product_id) ON DELETE RESTRICT,
    CONSTRAINT fk_transaction_user
        FOREIGN KEY (user_id) REFERENCES public.users(user_id) ON DELETE RESTRICT
);
CREATE INDEX IF NOT EXISTS idx_transactions_date ON public.inventory_transactions(transaction_date);
CREATE INDEX IF NOT EXISTS idx_transactions_product ON public.inventory_transactions(product_id);
CREATE INDEX IF NOT EXISTS idx_transactions_user ON public.inventory_transactions(user_id);

-- Compatibility helper for the first legacy inventory routines in migration
-- 001. Later migrations replace those routines with stockwise_inventory_status.
CREATE OR REPLACE FUNCTION public.inventory_status(
    p_quantity integer,
    p_minimum_stock integer
)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $function$
    SELECT CASE
        WHEN p_quantity <= 0 THEN 'Critical'
        WHEN p_quantity <= p_minimum_stock THEN 'Low stock'
        ELSE 'In stock'
    END;
$function$;


