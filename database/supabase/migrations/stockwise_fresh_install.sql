CREATE OR REPLACE FUNCTION public.organization_create_inventory(
    p_organization_id integer,
    p_product_name text,
    p_sku text,
    p_category_id integer,
    p_description text,
    p_price numeric,
    p_quantity integer,
    p_location_id integer,
    p_reorder_point integer,
    p_actor_email text
)
RETURNS TABLE(
    product_id integer, product_name text, sku text, category_id integer,
    description text, price numeric, quantity integer, reorder_point integer,
    location_id integer, location_name text, created_at timestamptz,
    updated_at timestamptz, category_name text, status text
)
LANGUAGE plpgsql
AS $function$
DECLARE
    v_product_id integer;
BEGIN
    IF NULLIF(btrim(p_product_name), '') IS NULL
       OR NULLIF(btrim(p_sku), '') IS NULL THEN
        RAISE EXCEPTION 'Product name and SKU are required'
            USING ERRCODE = '22023';
    END IF;
    IF p_price IS NULL OR p_quantity IS NULL OR p_reorder_point IS NULL
       OR p_price < 0 OR p_quantity < 0 OR p_reorder_point < 0 THEN
        RAISE EXCEPTION
            'Price, quantity, and reorder point must be non-negative'
            USING ERRCODE = '22023';
    END IF;
    IF NOT EXISTS (
        SELECT 1 FROM public.inventory_locations AS l
        WHERE l.organization_id = p_organization_id
          AND l.location_id = p_location_id AND l.is_active = true
    ) THEN
        RAISE EXCEPTION 'Inventory location was not found'
            USING ERRCODE = 'P0002';
    END IF;

    INSERT INTO public.products (
        organization_id, product_name, sku, category_id, description,
        price, quantity
    ) VALUES (
        p_organization_id, btrim(p_product_name), btrim(p_sku), p_category_id,
        p_description, p_price, p_quantity
    ) RETURNING products.product_id INTO v_product_id;

    INSERT INTO public.inventory_location_stock (
        organization_id, location_id, product_id, quantity, reorder_point
    )
    SELECT p_organization_id, l.location_id, v_product_id,
           CASE WHEN l.location_id = p_location_id THEN p_quantity ELSE 0 END,
           CASE WHEN l.location_id = p_location_id THEN p_reorder_point ELSE 50 END
    FROM public.inventory_locations AS l
    WHERE l.organization_id = p_organization_id AND l.is_active = true;

    IF p_quantity > 0 THEN
        INSERT INTO public.inventory_transactions (
            organization_id, location_id, product_id, user_id, actor_email,
            transaction_type, quantity, remarks
        ) VALUES (
            p_organization_id, p_location_id, v_product_id,
            (
                SELECT u.user_id FROM public.users AS u
                WHERE lower(u.email) = lower(btrim(p_actor_email))
                ORDER BY u.user_id LIMIT 1
            ),
            lower(btrim(p_actor_email)), 'IN', p_quantity, 'Opening stock'
        );
    END IF;

    RETURN QUERY SELECT * FROM public.organization_get_inventory_by_id(
        p_organization_id, v_product_id, p_location_id
    );
END;
$function$;

