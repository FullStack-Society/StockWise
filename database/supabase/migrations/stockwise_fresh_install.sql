CREATE OR REPLACE FUNCTION public.stockwise_purchase_order_history_trigger()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
DECLARE
    v_event_type text;
    v_actor text;
    v_details jsonb;
BEGIN
    IF TG_OP = 'INSERT' THEN
        v_event_type := 'created';
        v_actor := NEW.created_by_email;
        v_details := jsonb_build_object(
            'notes', NEW.notes,
            'items', COALESCE((
                SELECT jsonb_agg(jsonb_build_object(
                    'product_id', item.product_id,
                    'product_name', product.product_name,
                    'sku', product.sku,
                    'quantity_ordered', item.quantity_ordered,
                    'quantity_received', item.quantity_received
                ) ORDER BY item.item_id)
                FROM public.purchase_order_items AS item
                JOIN public.products AS product
                  ON product.organization_id = item.organization_id
                 AND product.product_id = item.product_id
                WHERE item.organization_id = NEW.organization_id
                  AND item.order_id = NEW.order_id
            ), '[]'::jsonb)
        );
    ELSIF OLD.deleted_at IS NULL AND NEW.deleted_at IS NOT NULL THEN
        v_event_type := 'deleted';
        v_actor := COALESCE(NEW.deleted_by_email, NEW.created_by_email);
        v_details := jsonb_build_object(
            'notes', NEW.notes,
            'items', COALESCE((
                SELECT jsonb_agg(jsonb_build_object(
                    'product_id', item.product_id,
                    'product_name', product.product_name,
                    'sku', product.sku,
                    'quantity_ordered', item.quantity_ordered,
                    'quantity_received', item.quantity_received
                ) ORDER BY item.item_id)
                FROM public.purchase_order_items AS item
                JOIN public.products AS product
                  ON product.organization_id = item.organization_id
                 AND product.product_id = item.product_id
                WHERE item.organization_id = NEW.organization_id
                  AND item.order_id = NEW.order_id
            ), '[]'::jsonb),
            'received_item_count', (
                SELECT count(*) FROM public.purchase_order_items AS item
                WHERE item.organization_id = NEW.organization_id
                  AND item.order_id = NEW.order_id
                  AND item.quantity_received > 0
            )
        );
    ELSE
        v_event_type := 'updated';
        v_actor := COALESCE(
            NULLIF(current_setting('app.actor_email', true), ''),
            NEW.created_by_email
        );
        v_details := jsonb_build_object(
            'notes', NEW.notes,
            'items', COALESCE((
                SELECT jsonb_agg(jsonb_build_object(
                    'product_id', item.product_id,
                    'product_name', product.product_name,
                    'sku', product.sku,
                    'quantity_ordered', item.quantity_ordered,
                    'quantity_received', item.quantity_received
                ) ORDER BY item.item_id)
                FROM public.purchase_order_items AS item
                JOIN public.products AS product
                  ON product.organization_id = item.organization_id
                 AND product.product_id = item.product_id
                WHERE item.organization_id = NEW.organization_id
                  AND item.order_id = NEW.order_id
            ), '[]'::jsonb)
        );
    END IF;

    INSERT INTO public.purchase_order_history (
        organization_id, order_id, event_type, actor_email, details
    ) VALUES (
        NEW.organization_id, NEW.order_id, v_event_type, v_actor, v_details
    );
    RETURN NEW;
END;
$function$;

