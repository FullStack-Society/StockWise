CREATE OR REPLACE FUNCTION public.org_leave(
    p_organization_id integer, p_email text
)
RETURNS boolean
LANGUAGE plpgsql
AS $function$
DECLARE
    v_role text;
    v_actor_email text := lower(btrim(p_email));
    v_actor_name text;
    v_organization_name text;
BEGIN
    SELECT role INTO v_role
    FROM public.organization_memberships
    WHERE organization_id = p_organization_id
      AND lower(email) = v_actor_email
      AND status = 'active';

    IF v_role IS NULL THEN RETURN FALSE; END IF;
    IF v_role = 'owner' THEN
        RAISE EXCEPTION 'The owner must transfer ownership before leaving'
            USING ERRCODE = '42501';
    END IF;

    SELECT COALESCE(
        (SELECT a.name
         FROM public.auth_users AS a
         WHERE lower(a.email) = v_actor_email
         ORDER BY a.id
         LIMIT 1),
        (SELECT u.full_name
         FROM public.users AS u
         WHERE lower(u.email) = v_actor_email
         ORDER BY u.user_id
         LIMIT 1),
        split_part(v_actor_email, '@', 1)
    )
    INTO v_actor_name;

    SELECT organization_name
    INTO v_organization_name
    FROM public.organizations
    WHERE organization_id = p_organization_id;

    INSERT INTO public.organization_leave_notifications (
        organization_id,
        recipient_email,
        actor_email,
        actor_name,
        organization_name
    )
    SELECT DISTINCT p_organization_id,
           lower(m.email),
           v_actor_email,
           v_actor_name,
           v_organization_name
    FROM public.organization_memberships AS m
    WHERE m.organization_id = p_organization_id
      AND m.status = 'active'
      AND m.role IN ('owner', 'manager')
      AND lower(m.email) <> v_actor_email;

    DELETE FROM public.organization_memberships
    WHERE organization_id = p_organization_id
      AND lower(email) = v_actor_email;
    RETURN TRUE;
END;
$function$;

